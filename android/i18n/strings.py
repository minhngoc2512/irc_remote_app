def android_escape(text: str) -> str:
    return escape(text).replace("'", "\\'").replace('"', '\\"')


def main():
    res = Path(__file__).resolve().parent.parent / "app" / "src" / "main" / "res"
    for i, lang in enumerate(LANGS):
        lines = ['<?xml version="1.0" encoding="utf-8"?>',
                 "<!-- Generated by android/i18n/strings.py: edit translations there. -->", "<resources>"]
        if lang == "en":
            lines.append('    <string name="app_name" translatable="false">EzRemote</string>')
        for key, values in S.items():
            assert len(values) == len(LANGS), key
            lines.append(f'    <string name="{key}">{android_escape(values[i])}</string>')
        for key, per_lang in P.items():
            value = per_lang[lang]
            one, other = value if isinstance(value, tuple) else (value, value)
            lines.append(f'    <plurals name="{key}">')
            if lang in ("en", "hi"):
                lines.append(f'        <item quantity="one">{android_escape(one)}</item>')
            lines.append(f'        <item quantity="other">{android_escape(other)}</item>')
            lines.append("    </plurals>")
        lines.append("</resources>")
        folder = res / FOLDER[lang]
        folder.mkdir(parents=True, exist_ok=True)
        (folder / "strings.xml").write_text("\n".join(lines) + "\n", encoding="utf-8")
    # Per-app language list for Android 13+ system settings.
    xml = res / "xml"
    xml.mkdir(exist_ok=True)
    tags = {"id": "in"}
    (xml / "locales_config.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n<locale-config xmlns:android="http://schemas.android.com/apk/res/android">\n'
        + "".join(f'    <locale android:name="{tags.get(l, l)}" />\n' for l in LANGS) + "</locale-config>\n",
        encoding="utf-8")
    print(f"{len(S)} strings, {len(P)} plurals x {len(LANGS)} languages")


if __name__ == "__main__":
    main()
