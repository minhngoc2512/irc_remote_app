"""Parsers that turn each upstream database into a common Codeset structure."""
from __future__ import annotations

import csv
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Iterator

from .encoders import Signal, UnsupportedProtocol, encode, encode_flipper
from .normalize import FLIPPER_CATEGORIES, irdb_category

MAX_GAP_US = 100_000  # trailing silence kept at the end of raw captures


@dataclass
class Button:
    label: str
    signal: Signal | None = None
    protocol: str = ""        # "" for raw captures
    params: str = ""          # e.g. "D=7,S=7,F=2"
    error: str = ""
    func_key: str | None = None  # set by sources that know the function; else derived from label


@dataclass
class Codeset:
    source: str               # key into SOURCES
    path: str                 # path inside the upstream repository
    brand: str                # raw brand spelling
    name: str
    category: str | None      # None = infer from buttons
    buttons: list[Button] = field(default_factory=list)


SOURCES = {
    "flipper": dict(name="Flipper-IRDB", url="https://github.com/Lucaslhm/Flipper-IRDB", license="CC0-1.0"),
    "flipper_converted": dict(name="Flipper-IRDB (_Converted_: Pronto, IR_Plus)",
                              url="https://github.com/Lucaslhm/Flipper-IRDB", license="CC0-1.0"),
    "irdb": dict(name="irdb by Simon Peter and contributors", url="https://github.com/probonopd/irdb",
                 license="irdb license (attribution + notify, see LICENSE.md upstream)"),
    "irremoteesp8266": dict(name="IRremoteESP8266 (A/C states generated by irremote/gen_ac.cpp)",
                            url="https://github.com/crankyoldgit/IRremoteESP8266", license="LGPL-2.1"),
}


# --- Flipper-IRDB ------------------------------------------------------------------

def _le_int(hex_bytes: str) -> int:
    return int.from_bytes(bytes.fromhex(hex_bytes.replace(" ", "")), "little")


def _raw_signal(freq: int, data: str) -> Signal:
    t = [abs(int(float(x))) for x in data.split()]
    t = [x for x in t if x > 0]
    if not t:
        raise ValueError("empty raw data")
    if len(t) % 2:  # transmit() expects mark/space pairs; close with a gap
        t.append(MAX_GAP_US)
    t[-1] = min(t[-1], MAX_GAP_US)
    return Signal(freq or 38000, t, t)


def parse_flipper_file(text: str) -> list[Button]:
    buttons: list[Button] = []
    cur: dict[str, str] = {}

    def flush():
        if "name" not in cur:
            return
        b = Button(label=cur["name"].strip())
        try:
            if cur.get("type") == "parsed":
                proto = cur["protocol"].strip()
                addr, cmd = _le_int(cur["address"]), _le_int(cur["command"])
                b.protocol, b.params = f"flipper:{proto}", f"A={addr},C={cmd}"
                b.signal = encode_flipper(proto, addr, cmd)
            elif cur.get("type") == "raw":
                b.signal = _raw_signal(int(float(cur.get("frequency", 38000))), cur["data"])
            else:
                b.error = f"unknown type {cur.get('type')!r}"
        except (UnsupportedProtocol, KeyError, ValueError) as e:
            b.error = f"{type(e).__name__}: {e}"
        buttons.append(b)

    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#") or ":" not in line:
            continue
        key, value = line.split(":", 1)
        key = key.strip().lower()
        if key == "name":
            flush()
            cur = {}
        if key == "data" and "data" in cur:  # some files wrap raw data over lines
            cur["data"] += " " + value
        else:
            cur[key] = value.strip()
    flush()
    return buttons


def _pretty(stem: str) -> str:
    return re.sub(r"[_]+", " ", stem).strip()


def iter_flipper(root: Path) -> Iterator[Codeset]:
    for path in sorted(root.rglob("*.ir")):
        rel = path.relative_to(root)
        parts = rel.parts
        if parts[0] == "_Converted_":
            # CSV/ is a conversion of irdb, which is read from upstream directly.
            if len(parts) < 4 or parts[1] not in ("Pronto", "IR_Plus"):
                continue
            source, category, brand = "flipper_converted", None, parts[3] if len(parts) > 4 else "Generic"
            name = " / ".join(_pretty(p) for p in parts[4:-1] + (path.stem,))
        else:
            if parts[0] not in FLIPPER_CATEGORIES:
                print(f"  ! unmapped Flipper folder {parts[0]}, using 'other'")
            category = FLIPPER_CATEGORIES.get(parts[0], "other")
            if category is None:
                continue
            source = "flipper"
            brand = parts[1] if len(parts) > 2 else "Generic"
            name = " / ".join(_pretty(p) for p in parts[2:-1] + (path.stem,))
        buttons = parse_flipper_file(path.read_text(errors="replace"))
        if buttons:
            yield Codeset(source, str(rel), brand, name, category, buttons)


# --- irdb ------------------------------------------------------------------------------

def _irdb_protocol(raw: str) -> tuple[str, dict]:
    """'Tivo unit=0' -> ('Tivo', {'U': 0}); plain names pass through."""
    tokens = raw.split()
    extra = {}
    for tok in tokens[1:]:
        if "=" in tok:
            k, v = tok.split("=", 1)
            extra[k[:1].upper()] = int(v)
    return (tokens[0] if tokens else ""), extra


def iter_irdb(root: Path) -> Iterator[Codeset]:
    codes = root / "codes"
    for path in sorted(codes.rglob("*.csv")):
        rel = path.relative_to(codes)
        if len(rel.parts) != 3:
            continue
        brand, type_folder, _ = rel.parts
        category = irdb_category(type_folder)
        model = type_folder[len("Unknown_"):] if type_folder.startswith("Unknown_") else type_folder
        name = f"{model} ({path.stem})"
        buttons: list[Button] = []
        with path.open(newline="", errors="replace") as fh:
            for row in csv.DictReader(fh):
                try:
                    proto, extra = _irdb_protocol(row["protocol"])
                    params = {"D": int(row["device"]), "S": int(row["subdevice"]), "F": int(row["function"]), **extra}
                    params = {k: v for k, v in params.items() if v >= 0}
                    b = Button(label=row["functionname"].strip(), protocol=proto,
                               params=",".join(f"{k}={v}" for k, v in params.items()))
                    b.signal = encode(proto, params)
                except (UnsupportedProtocol, KeyError, ValueError, TypeError) as e:
                    b = Button(label=(row.get("functionname") or "").strip(), protocol=row.get("protocol") or "",
                               error=f"{type(e).__name__}: {e}")
                buttons.append(b)
        if buttons:
            yield Codeset("irdb", f"codes/{rel}", brand, name, category, buttons)


# --- IRremoteESP8266 (generated A/C states) ------------------------------------------------

MIN_DISTINCT_AC_STATES = 10  # protocols whose default model ignores the settings are useless


def _ac_brands(supported_md: Path) -> dict[str, list[str]]:
    """SupportedProtocols.md has one table row per (source file, brand)."""
    brands: dict[str, list[str]] = {}
    for line in supported_md.read_text().splitlines():
        m = re.match(r"\| \[\w+\]\(.*?/src/ir_(\w+)\.cpp\) \| \*\*\[([^\]]+)\]", line)
        if m:
            brands.setdefault(m.group(1).lower(), []).append(m.group(2))
    return brands


def _ac_remote_hints(src: Path) -> dict[tuple[str, str], list[str]]:
    """'Model: A75C3704 remote (PANASONIC_AC DKE/3)' comments -> {(PROTO, MODEL): [remote names]}."""
    hints: dict[tuple[str, str], list[str]] = {}
    for header in src.glob("ir_*.h"):
        for m in re.finditer(r"Model: ([^(\n]+?) \((\w+) ([\w-]+)/\d+\)", header.read_text(errors="replace")):
            hints.setdefault((m.group(2), m.group(3).upper()), []).append(m.group(1).strip())
    return hints


def _panasonic_patch(timings: list[int], byte_index: int, value: int) -> list[int]:
    """Rewrite one byte of a Panasonic A/C data frame and fix its checksum (sum of bytes mod 256).

    Panasonic frames: header mark > 2500 µs, then pulse-distance bits LSB first;
    the data frame is the last one and its final byte is the checksum.
    """
    t = list(timings)
    frames: list[list[int]] = []  # per frame: indices of the space that encodes each bit
    for i in range(0, len(t) - 1, 2):
        if t[i] > 2500:
            frames.append([])
        elif frames and t[i + 1] < 5000:
            frames[-1].append(i + 1)
    spaces = frames[-1]
    zero, one = min(t[i] for i in spaces), max(t[i] for i in spaces)
    data = [sum((t[spaces[b * 8 + k]] > (zero + one) / 2) << k for k in range(8)) for b in range(len(spaces) // 8)]
    data[byte_index] = value
    data[-1] = sum(data[:-1]) & 0xFF
    for b, byte in enumerate(data):
        for k in range(8):
            t[spaces[b * 8 + k]] = one if (byte >> k) & 1 else zero
    return t


# Real captures of Vietnamese "nanoe-G" inverter remotes (Flipper-IRDB
# Panasonic_CWA75C4179.ir) match RKR except data byte 15 = 0x81 instead of 0x89.
_DERIVED_AC = {
    "PANASONIC_AC#A75C4xxx": ("PANASONIC_AC#RKR", lambda t: _panasonic_patch(t, 15, 0x81),
                              "remote nanoe-G A75C4xxx (A75C4179, A75C4187…)"),
}


def iter_irremoteesp8266(lib_root: Path, states_tsv: Path) -> Iterator[Codeset]:
    if not states_tsv.exists():
        print(f"  ! {states_tsv} missing — run irremote/build_ac.sh; skipping IRremoteESP8266")
        return
    file_brands = _ac_brands(lib_root / "SupportedProtocols.md")
    hints = _ac_remote_hints(lib_root / "src")
    by_proto: dict[str, list[Button]] = {}
    for line in states_tsv.read_text().splitlines():
        proto, label, params, freq, timings = line.split("\t")
        merged: list[int] = []
        for v in map(int, timings.split(",")):
            if merged and (merged[-1] > 0) == (v > 0):
                merged[-1] += v
            else:
                merged.append(v)
        t = [abs(v) for v in merged]
        if len(t) % 2:
            t.append(MAX_GAP_US)
        t[-1] = min(t[-1], MAX_GAP_US)
        by_proto.setdefault(proto, []).append(Button(
            label=label, signal=Signal(int(freq), t, t), protocol=f"IRremoteESP8266:{proto}", params=params,
            func_key="POWER_OFF" if params == "power=0" else "AC"))

    for derived, (parent, patch, hint) in _DERIVED_AC.items():
        if parent in by_proto:
            by_proto[derived] = []
            for b in by_proto[parent]:
                t = patch(b.signal.intro)
                by_proto[derived].append(Button(b.label, Signal(b.signal.freq, t, t), b.protocol.replace(parent.split("#")[1], derived.split("#")[1]),
                                                b.params, func_key=b.func_key))
            base, _, model = derived.partition("#")
            hints[(base, model.upper())] = [hint]
            # Matched against real captures, so offer it before the generic models.
            by_proto = {derived: by_proto.pop(derived), **by_proto}

    for proto, buttons in by_proto.items():
        if len({tuple(b.signal.intro) for b in buttons}) < MIN_DISTINCT_AC_STATES:
            print(f"  ! {proto}: settings have no effect with the default model, skipped")
            continue
        base, _, model = proto.partition("#")
        key = re.sub(r"[^a-z0-9]", "", base.lower())
        source_file = max((f for f in file_brands if key.startswith(f)), key=len, default=None)
        name = f"{base} {model}".strip()
        remotes = hints.get((base, model.upper()), [])
        if remotes:
            name += " · " + ", ".join(remotes)
        for brand in file_brands.get(source_file, [base.split("_")[0].title()]):
            yield Codeset("irremoteesp8266", f"src/ir_{source_file}.cpp#{proto}", brand, name, "ac", buttons)
